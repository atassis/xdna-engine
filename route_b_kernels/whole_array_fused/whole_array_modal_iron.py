def _stack_size():
    """Per-core stack reservation, overridable via WA_STACK_SIZE.

    0xD00 is a POLICY, not a derivation -- it is copy-pasted across 14 sites in this tree with no
    recorded frame measurement behind it. That matters because the generated linker script places the
    stack directly below the objectFIFO buffers with ZERO clearance (measured: 4874 of 4881 core
    scripts), so this number is the only thing between a kernel frame and silent buffer corruption --
    no crash, deterministic, surviving tiles bit-exact. Overridable so a suspected overflow can be
    tested in one build instead of being argued about.
    """
    import os as _os
    return int(_os.environ.get("WA_STACK_SIZE", "0xD00"), 0)


def _trace_event(spec):
    """One --trace_events item: a bare CoreEvent name, or a PORT_* event bound to a port.

    A PORT_* name selects a monitor SLOT, not a port -- the slot counts nothing until it is
    pointed at one. The default core set binds slot 0 to DMA ch0 in and slot 1 to DMA ch0 OUT
    (aie.utils.trace.setup), so `PORT_RUNNING_1` alone does not mean channel 1 and the second
    input channel is unreachable by name. Bind it explicitly as NAME:BUNDLE:CHANNEL:DIR, e.g.
    PORT_RUNNING_1:DMA:1:in.

    This design puts A on S2MM ch0 and B on S2MM ch1 (one dma_start each, in the generated
    aie.mem), so a run without an explicit ch1 binding measures the A feed alone.

    Events sharing a slot must agree on the binding -- PORT_RUNNING_0 and PORT_STALLED_0 both
    watch slot 0, which is how running-vs-backpressured is read off one port.
    """
    from aie.dialects.aie import WireBundle
    from aie.utils.trace.events import CoreEvent, PortEvent

    parts = [p.strip() for p in spec.split(":")]
    code = getattr(CoreEvent, parts[0])
    if len(parts) == 1:
        return code
    if len(parts) != 4:
        raise ValueError(f"port event wants NAME:BUNDLE:CHANNEL:DIR, got {spec!r}")
    bundle, channel, direction = parts[1], int(parts[2]), parts[3].lower()
    if direction not in ("in", "out"):
        raise ValueError(f"direction is in|out, got {parts[3]!r} in {spec!r}")
    return PortEvent(
        code, port=getattr(WireBundle, bundle), channel=channel, master=(direction == "in")
    )


def _memtile_trace_event(spec):
    """One --trace_memtile_events item, in MemTileEvent space rather than CoreEvent space.

    Same NAME[:BUNDLE:CHANNEL:DIR] grammar as _trace_event, and the same trap: a PORT_* name is a
    monitor SLOT. The memtile default set binds slots 0-3 to DMA ch0-3 IN and 4-7 to ch0-3 OUT, so
    an unbound PORT_RUNNING_1 watches an INPUT channel here.

    DIR follows aie.utils.trace.setup's own convention -- master=True is "in" (S2MM), False is
    "out" (MM2S). This design pushes A on memtile MM2S ch0 and B on MM2S ch1, so the two feeds at
    their SOURCE are PORT_RUNNING_x:DMA:0:out and :DMA:1:out.

    The DMA_MM2S_SEL{0,1}_* counters are a SEPARATE mechanism: which channel each SEL watches comes
    from the memtile's DMA_EVENT_CHANNEL_SELECTION register, which mlir-aie never writes, so they
    sit at the reset default. Treat that as unverified and gate it -- pair each SEL event with the
    explicitly-bound PORT_RUNNING for the channel it is supposed to be, and check the windows agree.
    """
    from aie.dialects.aie import WireBundle
    from aie.utils.trace.events import MemTileEvent, MemTilePortEvent

    parts = [p.strip() for p in spec.split(":")]
    code = getattr(MemTileEvent, parts[0])
    if len(parts) == 1:
        return code
    if len(parts) != 4:
        raise ValueError(f"port event wants NAME:BUNDLE:CHANNEL:DIR, got {spec!r}")
    bundle, channel, direction = parts[1], int(parts[2]), parts[3].lower()
    if direction not in ("in", "out"):
        raise ValueError(f"direction is in|out, got {parts[3]!r} in {spec!r}")
    return MemTilePortEvent(
        code, port=getattr(WireBundle, bundle), channel=channel, master=(direction == "in")
    )


